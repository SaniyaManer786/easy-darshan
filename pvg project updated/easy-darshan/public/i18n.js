let currentLang = "en";

function t(key) {
  const pack = TRANSLATIONS[currentLang] || TRANSLATIONS.en;
  if (pack[key] != null) return pack[key];
  if (TRANSLATIONS.en[key] != null) return TRANSLATIONS.en[key];
  return key;
}

function faqT(id, which) {
  const pack = FAQ_COPY[currentLang] || FAQ_COPY.en;
  const k = id + "_" + which;
  if (pack[k] != null) return pack[k];
  return (FAQ_COPY.en && FAQ_COPY.en[k]) || "";
}

function applyI18n(lang) {
  if (lang) {
    currentLang = TRANSLATIONS[lang] ? lang : "en";
    try {
      localStorage.setItem("ed_lang", currentLang);
    } catch (e) {
      /* ignore */
    }
  }
  const htmlLang = currentLang === "hi" ? "hi" : currentLang === "mr" ? "mr" : "en";
  document.documentElement.lang = htmlLang;
  const sel = document.querySelector(".lang-sel");
  if (sel && sel.value !== currentLang) sel.value = currentLang;

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const k = el.getAttribute("data-i18n");
    const v = t(k);
    if (el.hasAttribute("data-i18n-html")) el.innerHTML = v;
    else el.textContent = v;
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.setAttribute("placeholder", t(el.getAttribute("data-i18n-placeholder")));
  });
  document.querySelectorAll("[data-i18n-title]").forEach((el) => {
    el.setAttribute("title", t(el.getAttribute("data-i18n-title")));
  });
}

function initI18n() {
  let lang = "en";
  try {
    lang = localStorage.getItem("ed_lang") || "en";
  } catch (e) {
    lang = "en";
  }
  applyI18n(lang);
}

if (typeof window !== "undefined") {
  window.t = t;
  window.faqT = faqT;
  window.applyI18n = applyI18n;
  window.initI18n = initI18n;
}

